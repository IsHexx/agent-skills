import openpyxl
from openpyxl import Workbook

COLUMNS = ["编号", "目录", "优先级", "标题", "前置条件", "步骤描述", "预期结果", "负责人", "用例类型"]


def add_sheet(wb: Workbook, name: str, rows: list[dict]) -> None:
    ws = wb.create_sheet(title=name)
    ws.append(COLUMNS)
    for row in rows:
        ws.append([row.get(c, "") for c in COLUMNS])

    widths = {
        "编号": 10,
        "目录": 18,
        "优先级": 6,
        "标题": 52,
        "前置条件": 48,
        "步骤描述": 48,
        "预期结果": 48,
        "负责人": 8,
        "用例类型": 12,
    }
    for idx, col in enumerate(COLUMNS, start=1):
        ws.column_dimensions[openpyxl.utils.get_column_letter(idx)].width = widths.get(col, 18)
    ws.freeze_panes = "A2"


def tc_id(n: int) -> str:
    return f"TC-{n:03d}"


def pre(system: str, perm: str, data: str) -> str:
    return f"1. 系统状态：{system}\n2. 权限配置：{perm}\n3. 数据准备：{data}"


def steps(*items: str) -> str:
    return "\n".join([f"{i}. {s}" for i, s in enumerate(items, start=1)])


def expect(*items: str) -> str:
    return "\n".join([f"{i}. {s}" for i, s in enumerate(items, start=1)])


